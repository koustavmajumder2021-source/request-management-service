CREATE SEQUENCE publication_number_seq START WITH 1 INCREMENT BY 1;

CREATE TABLE requests (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name               VARCHAR(255)   NOT NULL,
    content            VARCHAR(10000) NOT NULL,
    state              VARCHAR(20)    NOT NULL,
    reason             VARCHAR(1000),
    publication_number BIGINT,
    created_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    version            BIGINT         NOT NULL,
    CONSTRAINT uk_requests_publication_number UNIQUE (publication_number),
    CONSTRAINT ck_requests_state CHECK (state IN ('CREATED', 'VERIFIED', 'ACCEPTED', 'PUBLISHED', 'REJECTED', 'DELETED')),
    CONSTRAINT ck_requests_publication_number CHECK ((state = 'PUBLISHED') = (publication_number IS NOT NULL))
);

CREATE INDEX ix_requests_state ON requests (state);
CREATE INDEX ix_requests_name ON requests (name);

CREATE TABLE request_state_changes (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id  BIGINT      NOT NULL REFERENCES requests (id),
    action      VARCHAR(20) NOT NULL,
    from_state  VARCHAR(20),
    to_state    VARCHAR(20) NOT NULL,
    reason      VARCHAR(1000),
    occurred_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX ix_request_state_changes_request_id ON request_state_changes (request_id);
